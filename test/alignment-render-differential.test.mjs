// @test-kind contract: Lense's live alignment (lense/response-alignment.mjs) against the Mirage render of the same export as ground truth: for every element of every page the render binds, the alignment of the served HTML names the same source and place, or a less precise true answer, and never another source or place
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { tempDirSync } from './fixture.mjs';
import { differential } from './fixtures/render-oracle.mjs';
import {
  DYNAMIC_PAGES,
  EDITOR,
  EXAMPLE_PROJECT,
  exportRenderer,
  writeDynamicPortal,
} from './fixtures/dynamic-liquid-portal.mjs';

const ACCOUNT = 'a4300000-0000-4000-8000-000000001001';
const NATIVE = '/approach/out-of-the-box/account/';

/** Per page and identity: AGREE / WEAKER / MISS / WRONG / UNBOUND counts. */
async function table(t, renderer, urls) {
  const rows = {};
  const reasons = {};
  for (const url of urls)
    for (const signed of [false, true]) {
      const result = await differential(renderer, url, signed ? structuredClone(EDITOR) : null);
      assert.ok(result, `${url} renders with provenance`);
      assert.equal(result.plain, result.served, `${url}: without its marks the render is the served document`);
      const key = `${url} ${signed ? 'signed in' : 'anonymous'}`;
      rows[key] = Object.values(result.counts).join('/');
      for (const row of result.rows)
        if (row.verdict !== 'AGREE') {
          const reason = `${row.verdict} ${row.reason}`;
          reasons[reason] = (reasons[reason] ?? 0) + 1;
        }
      const wrong = result.rows.filter((row) => row.verdict === 'WRONG' || row.verdict === 'UNBOUND');
      assert.deepEqual(
        wrong.map((row) => `${result.plain.slice(row.start, row.start + 60).split('>')[0]}> ${row.reason}`),
        [],
        `${key}: no element is attributed to another source or place`,
      );
    }
  for (const [key, counts] of Object.entries(rows)) t.diagnostic(`${key}: AGREE/WEAKER/MISS/WRONG/UNBOUND ${counts}`);
  for (const [reason, count] of Object.entries(reasons).sort((a, b) => b[1] - a[1])) t.diagnostic(`${count} ${reason}`);
  return rows;
}

test('every page of examples/project: the live alignment agrees with the render, anonymous and signed in', async (t) => {
  const { portal, renderer } = await exportRenderer(path.join(EXAMPLE_PROJECT, 'portal'));
  const urls = [
    ...portal.pages.map((page) => page.url),
    `${NATIVE}?mode=create`,
    `${NATIVE}?id=${ACCOUNT}&mode=edit`,
    `${NATIVE}?id=${ACCOUNT}`,
  ];
  assert.deepEqual(await table(t, renderer, urls), EXAMPLE_COUNTS);
});

test('pages generated by Liquid conditions, loops, includes, captures and components over data agree with the render', async (t) => {
  const dir = tempDirSync('paqvilo-dynamic-');
  t.after(() => fs.rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 }));
  const { renderer } = await exportRenderer(writeDynamicPortal(path.join(dir, 'portal')));
  assert.deepEqual(await table(t, renderer, DYNAMIC_PAGES), DYNAMIC_COUNTS);
});

