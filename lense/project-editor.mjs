import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { DEV_BACKGROUND } from './dev-messages.mjs';
import { assertScaffoldPath } from './scaffold.mjs';
import { loadCatalogue } from './config.mjs';
import { resolveCatalogue } from './resolved-catalogue.mjs';

const json = value => JSON.stringify(value, null, 2) + '\n';
const digest = value => createHash('sha256').update(json(value)).digest('hex');
function owned(value) {
  return json({ ...value, paqvilo: { scaffold: 1, generatedHash: digest(value) } });
}
function unedited(body) {
  try {
    const { paqvilo, ...value } = JSON.parse(body);
    return paqvilo?.scaffold === 1 && paqvilo.generatedHash === digest(value);
  } catch { return false; }
}

export function editorFiles({ name, sites, browser, sourceRoot, scripts, folders = ['.'] }) {
  const prefix = name[0].toUpperCase() + name.slice(1);
  const label = script => `${prefix}: ${script}`;
  const tasks = Object.keys(scripts).map(script => {
    const background = /^(?:dev|mirage:dev)(?::|$)/.test(script) && script !== 'dev:pick';
    return { label: label(script), type: 'npm', script, options: { cwd: '${workspaceFolder}' },
      ...(background ? { isBackground: true, problemMatcher: { owner: 'paqvilo', pattern: { regexp: '^(?!)$', file: 1, location: 2, message: 3 }, background: DEV_BACKGROUND } } : { problemMatcher: [] }) };
  });
  const configurations = [];
  for (const product of ['dev', 'mirage:dev']) {
    for (const site of [null, ...sites]) {
      const script = site ? `${product}:${site}:debug` : `${product}:debug`;
      if (!scripts[script]) continue;
      configurations.push({ name: label(script), type: browser === 'msedge' ? 'msedge' : 'chrome', request: 'attach',
        port: product === 'dev' ? 9222 : 9223, webRoot: sourceRoot, preLaunchTask: label(script),
        skipFiles: ['**/bootstrap*.js', '**/jquery*.js', '**/*.min.js'] });
    }
  }
  return {
    '.vscode/tasks.json': owned({ version: '2.0.0', tasks }),
    '.vscode/launch.json': owned({ version: '0.2.0', configurations }),
    [`${name}.code-workspace`]: owned({ folders: folders.map(folder => ({ path: folder })) }),
  };
}

export async function refreshEditor(directory, { config, workspaceOnly = false, processEnv = process.env } = {}) {
  const target = await assertScaffoldPath(directory, { directory: true });
  const manifest = JSON.parse(await fs.readFile(path.join(target, 'package.json'), 'utf8'));
  if (manifest.paqvilo?.scaffold !== 1) throw new Error('Editor refresh requires a package generated by paqvilo init (scaffold 1).');
  if (!/^[a-z0-9][a-z0-9-]{0,63}$/.test(manifest.name)) throw new Error('Editor refresh requires a portable scaffold package name.');
  if (manifest.paqvilo.vscode === false && !workspaceOnly) throw new Error('This scaffold disabled VS Code generation.');
  const configFile = path.resolve(target, config ?? 'paqvilo.config.yml');
  const catalogue = loadCatalogue({ config: configFile }, processEnv);
  const resolved = await resolveCatalogue({ config: configFile }, processEnv);
  const candidates = [target, resolved.sourceRoot, ...resolved.sites.flatMap(site => [site.sourceDir, ...site.solutionRoots])];
  const folders = [], realFolders = new Set();
  for (const folder of candidates.filter(Boolean)) {
    try {
      if (!(await fs.stat(folder)).isDirectory()) continue;
      const real = await fs.realpath(folder);
      if (!realFolders.has(real)) { realFolders.add(real); folders.push(folder); }
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  const files = editorFiles({ name: manifest.name, sites: resolved.sites.map(site => site.name),
    browser: catalogue.settings.values.PAQVILO_BROWSER ?? catalogue.root.browser.channel,
    sourceRoot: resolved.sourceRoot, scripts: manifest.scripts ?? {}, folders });
  const created = [], updated = [], skipped = [], conflicts = [];
  for (const [name, body] of Object.entries(files)) {
    if (workspaceOnly && !name.endsWith('.code-workspace')) continue;
    const file = path.join(target, name);
    await assertScaffoldPath(file);
    let existing;
    try { existing = await fs.readFile(file, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (existing === body) { skipped.push(name); continue; }
    let destination = file;
    let destinationExists = existing !== undefined;
    if (existing !== undefined && !unedited(existing)) {
      destination = name.endsWith('.json') ? file.replace(/\.json$/, '.generated.json') : file.replace(/\.code-workspace$/, '.generated.code-workspace');
      conflicts.push({ file: name, generated: path.relative(target, destination).replaceAll('\\', '/') });
      await assertScaffoldPath(destination);
      let alternate;
      try { alternate = await fs.readFile(destination, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
      destinationExists = alternate !== undefined;
      if (alternate !== undefined && !unedited(alternate)) { skipped.push(path.relative(target, destination).replaceAll('\\', '/')); continue; }
    }
    await fs.mkdir(path.dirname(destination), { recursive: true });
    await fs.writeFile(destination, body, { flag: destinationExists ? 'w' : 'wx' });
    (existing === undefined ? created : updated).push(path.relative(target, destination).replaceAll('\\', '/'));
  }
  return { schemaVersion: 1, ok: true, directory: target, created, updated, skipped, conflicts };
}
