// @test-kind contract: on a live portal whose pages Liquid generates from conditions, loops, includes, captures and platform components over data, X-ray names for each such element the file, line and kind of answer the Mirage render of the same export binds it to, in two data states, and leaves no element of the page unidentified
import { test } from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import path from 'node:path';
import { listenOwnedServer } from './helpers/owned-server.mjs';
import { overlayPanel } from './helpers/overlay-panel.mjs';
import { createFixture } from '../test/fixture.mjs';
import {
  DYNAMIC,
  DYNAMIC_FILES,
  EDITOR,
  exportRenderer,
  writeDynamicPortal,
} from '../test/fixtures/dynamic-liquid-portal.mjs';
import { differential } from '../test/fixtures/render-oracle.mjs';

const FOUND = 'Found at this place in the served page';
const GENERATED = 'Generated by this Liquid code';
const SIGNED_IN = 'invented-persona=editor';

// The elements a test names, by page: a selector X-ray is asked about, and the start of the tag the render binds (or
// a pattern of its start tag).
const NAMED = {
  '/dyn/alpha/': {
    loopRow: ['#dyn-colors > li', '<li class="dyn-color'],
    nestedLoopItem: ['#dyn-grid .dyn-cell', '<span class="dyn-cell"'],
    branch: ['.dyn-greeting', '<p class="dyn-greeting'],
    caseBranch: ['.dyn-case', '<span class="dyn-case"'],
    unlessBranch: ['.dyn-signin', '<a class="dyn-signin"'],
    partialTwice: ['#dyn-cards > article', '<article class="dyn-card'],
    partialInLoop: ['#dyn-looped > article', '<article class="dyn-card'],
    snippetInLoop: ['#dyn-looped > small', '<small class="dyn-note"'],
    captured: ['#dyn-capture > strong', '<strong class="dyn-banner"'],
    capturedFiltered: ['#dyn-capture-changed > strong', '<strong class="dyn-banner"'],
    dynamicAttributes: ['#dyn-attrs', '<div class="dyn-attrs'],
    emptyLoopElse: ['#dyn-empty > li', '<li class="dyn-empty-else"'],
    recordRows: ['#dyn-rows tr', '<tr class="dyn-account-row"'],
    tablerow: ['#dyn-table tr', '<tr class="row'],
  },
  '/dyn/gamma/': {
    branch: ['.dyn-greeting', '<p class="dyn-greeting'],
    loopRow: ['#dyn-colors > li', '<li class="dyn-color'],
    formPart: ['#dyn-form [id^="EntityFormControl"]', /^<\w+ [^>]*id="EntityFormControl/],
    afterForm: ['#dyn-form .dyn-form-after', '<p class="dyn-form-after"'],
    partialInLoop: ['#dyn-account-cards > article', '<article class="dyn-card'],
  },
};

test('X-ray identifies the elements Liquid generates from conditions, loops, includes and components, as the render binds them', async (t) => {
  const fx = createFixture();
  writeDynamicPortal(fx.dir);
  fx.commit();
  const { renderer } = await exportRenderer(fx.dir);
  const index = renderer.sourceIndex();
  const signedIn = (request) => (request.headers.cookie ?? '').includes(SIGNED_IN);
  // The "portal": pages rendered in process by Mirage from the same export, without provenance marks.
  const server = http.createServer((request, response) => {
    const url = new URL(request.url, 'http://fixture.invalid');
    if (url.pathname.startsWith('/resource/powerappsportal/'))
      return response.writeHead(200, { 'content-type': 'text/javascript' }).end('window.portalRuntime = true;');
    if (!(url.pathname in NAMED)) return response.writeHead(404, { 'content-type': 'text/plain' }).end('not found');
    differential(renderer, url.pathname, signedIn(request) ? structuredClone(EDITOR) : null).then(
      (result) => response.writeHead(200, { 'content-type': 'text/html' }).end(result.plain),
      (error) => response.writeHead(500, { 'content-type': 'text/plain' }).end(String(error)),
    );
    return undefined;
  });
  const { origin, context, page, panel, errors } = await overlayPanel(t, fx, () => listenOwnedServer(t, server));

  const relative = (file) => path.relative(fx.dir, file).split(path.sep).join('/');
  const lineAt = (text, at) => text.slice(0, at).split(/\r\n|\r|\n/).length;
  // What the render binds each named element to, as X-ray would show it.
  const expected = (result, selector, startOfTag) => {
    // `#container child`: only the tags inside the element with that id.
    const container = /^#([\w-]+)\s/.exec(selector)?.[1];
    const inside = (row) => {
      for (let up = row.parent; up; up = up.parent)
        if (result.plain.slice(up.start, result.plain.indexOf('>', up.start)).includes(`id="${container}"`))
          return true;
      return false;
    };
    return result.rows
      .filter((row) => {
        const tag = result.plain.slice(row.start, result.plain.indexOf('>', row.start) + 1);
        const named = startOfTag instanceof RegExp ? startOfTag.test(tag) : tag.startsWith(startOfTag);
        return named && (!container || inside(row));
      })
      .map(({ binding }) => {
        const source = index.sources.get(binding.sourceRefId ?? binding.sourceRefIds?.[0]);
        if (binding.mapping === 'literal')
          return { file: relative(source.file), line: binding.region.line, how: FOUND };
        if (binding.mapping === 'derived')
          return { file: relative(source.file), line: binding.region.line, how: GENERATED };
        // A part of a platform component: the render names its configuration; the page names the Liquid tag that
        // renders the component, in the template that holds it.
        const tag = '{% entityform ';
        const template = DYNAMIC_FILES[DYNAMIC.page];
        return {
          file: DYNAMIC.page,
          line: lineAt(template, template.indexOf(tag)),
          how: 'Generated by the entityform tag',
        };
      });
  };
  const answers = (selectors) =>
    page.evaluate((named) => {
      const xray = globalThis.__paqviloXrayUi;
      const answer = (node) => {
        const exact = xray.identify(node).evidence.source.refs.find((ref) => ref.status === 'exact');
        return exact
          ? { file: exact.ref.replaceAll('\\', '/'), line: exact.region?.line, how: exact.evidenceLabel }
          : null;
      };
      return Object.fromEntries(
        Object.entries(named).map(([name, [selector]]) => [name, [...document.querySelectorAll(selector)].map(answer)]),
      );
    }, selectors);
  // The page is identified once its inspection report is in and the proof of this document is published.
  const identified = async () => {
    await page.waitForFunction(() => typeof globalThis.__paqviloXrayUi?.coverage === 'function');
    const first = await panel.coverageFor(page);
    await page.waitForFunction(
      () => globalThis.__paqviloXrayUi.identify(document.querySelector('#dyn-main')).evidence.source.status === 'exact',
    );
    return first.available ? panel.coverageFor(page, { samples: 8 }) : first;
  };

  for (const [route, persona] of [
    ['/dyn/alpha/', null],
    ['/dyn/gamma/', SIGNED_IN],
  ]) {
    await context.clearCookies();
    if (persona) {
      const [name, value] = persona.split('=');
      await context.addCookies([{ name, value, url: origin }]);
    }
    const oracle = await differential(renderer, route, persona ? structuredClone(EDITOR) : null);
    await page.goto(origin + route, { waitUntil: 'load' });
    const coverage = await identified();
    const got = await answers(NAMED[route]);
    for (const [name, [selector, startOfTag]] of Object.entries(NAMED[route])) {
      const want = expected(oracle, selector, startOfTag);
      assert.ok(want.length > 0, `${route} ${name}: the render writes ${selector}`);
      assert.deepEqual(got[name], want, `${route} ${name} (${selector})`);
    }
    assert.equal(
      coverage.counts.none + coverage.counts.likely + coverage.counts.conflict,
      0,
      `${route}: ${JSON.stringify(coverage)}`,
    );
    assert.equal(coverage.counts.direct + coverage.counts.contained, coverage.total);
  }
  // The two data states rendered different branches and loop counts.
  const alpha = await differential(renderer, '/dyn/alpha/', null);
  const gamma = await differential(renderer, '/dyn/gamma/', structuredClone(EDITOR));
  assert.ok(alpha.plain.includes('dyn-greeting alpha') && gamma.plain.includes('dyn-greeting signed'));
  assert.ok(!alpha.plain.includes('id="dyn-form"') && gamma.plain.includes('id="dyn-form"'));
  assert.deepEqual(errors, []);
});
